// Builds all app pages from the SAME Hub 16.0 shell and original source compartments.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const base = path.join(root, 'apps/_hub');
const read = p => fs.readFileSync(path.join(base, p), 'utf8');
const modules = ['shell', 'layout', 'widgets', 'telemetry', 'widget-controls', 'operations-register', 'interactions', 'background'];
const body = modules.map(n => read(`src/${n}.js`)).join('\n');
fs.writeFileSync(path.join(base, 'hub.js'), `// Generated by tools/build-operations.cjs.\n(()=>{\nconst localStorage = window.OpsLayoutStorage;\n${body}\n})();\n`);
for (const [route,title] of [['','Apps'],['crm','CRM'],['photo-center','Photo Center'],['estimates','Estimates']]) {
  let html = read('shell.html').replace(/<title>[\s\S]*?<\/title>/, `<title>${title} · TAGIMS</title>`);
  html = html.replace(/<link[^>]+fonts\.googleapis[^>]*>/g, '');
  html = html.replace(/<link[^>]+finance\/native\/widgets.css[^>]*>/g, '');
  html = html.replace(/<script[^>]+src="(?:finance\/native\/[^\"]+|hub.js)"[^>]*><\/script>/g, '');
  html = html.replaceAll('href="css/', 'href="/apps/_hub/css/');
  html = html.replaceAll('assets/backgrounds/image.jpg', '');
  html = html.replace(/<button class="widget-library-item"[\s\S]*?<\/button>/g, '');
  html = html.replace('</head>', '<link rel="stylesheet" href="/apps/_hub/operations.css"></head>');
  html = html.replace('</body>', `<script src="/apps/_hub/config.js"></script><script src="/apps/_hub/domain.js"></script><script src="/apps/_hub/store.js"></script><script src="/apps/_hub/prototype-import.js"></script><script src="/apps/_hub/operations.js"></script><script src="/apps/_hub/bootstrap.js"></script><script src="/apps/_hub/hub.js"></script></body>`);
  const dest = path.join(root, 'apps', route); fs.mkdirSync(dest, {recursive:true}); fs.writeFileSync(path.join(dest, 'index.html'), html);
}
console.log('Built four app pages with the shared Hub shell.');
